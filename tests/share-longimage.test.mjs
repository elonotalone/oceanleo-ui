test("R6 宽表：先整体等比缩放", () => {
  // 9 列 × 87px ≈ 785px，比 646px 的正文宽略宽一点：应当整体缩放而不是裁列。
  const columns = Array.from({ length: 9 }, () => [
    "标题标题标题",
    "内容内容内容内容",
  ]);
  const plan = planTableColumns(columns, 646, measure, 14);
  assert.equal(plan.keptColumns, plan.totalColumns);
  assert.ok(plan.font.size < 14, "放不下时字号要缩小");
  assert.ok(plan.font.size >= SHARE_MIN_TABLE_FONT);
  const total = plan.widths.reduce((sum, width) => sum + width, 0);
  assert.ok(total <= 646 + 1);
});

test("R6 宽表：缩到最小可读字号仍放不下 → 保留前若干列并标注", () => {
  const wide = [
    ["月份", "1 月"],
    ...Array.from({ length: 24 }, (_, index) => [
      `很长的表头名称 ${index}`,
      `很长的数据单元格内容 ${index}`,
    ]),
  ];
  const plan = planTableColumns(wide, 646, measure, 14);
  assert.equal(plan.font.size, SHARE_MIN_TABLE_FONT);
  assert.ok(plan.keptColumns < plan.totalColumns);
  assert.ok(plan.keptColumns >= 1);

  const header = wide.map((column) => column[0]);
  const row = wide.map((column) => column[1]);
  const markdown = [
    `| ${header.join(" | ")} |`,
    `| ${header.map(() => "---").join(" | ")} |`,
    `| ${row.join(" | ")} |`,
  ].join("\n");
  const result = layoutShareCard(conversation(markdown), labels, measure);
  assert.equal(result.truncatedTables, 1);
  assert.ok(
    result.pages.some((page) => allTexts(page).includes("完整表格见原对话")),
  );
});

test("R6 超长：单页不超过 12000px，超出自动分片并标 i/N", () => {
  const long = Array.from(
    { length: 400 },
    (_, index) => `第 ${index} 段：这是一段足够长的正文，用来把长图撑过一页的高度上限。`,
  ).join("\n\n");
  const result = layoutShareCard(conversation(long), labels, measure);
  assert.ok(result.pages.length >= 2, "应当切成多张");
  for (const page of result.pages) {
    assert.ok(
      page.height <= SHARE_MAX_PAGE_HEIGHT,
      `第 ${page.index} 张高 ${page.height}，超过了 12000`,
    );
  }
  const total = result.pages.length;
  for (const page of result.pages) {
    assert.ok(
      allTexts(page).includes(`${page.index}/${total}`),
      `第 ${page.index} 张缺页码`,
    );
  }
  assert.deepEqual(
    result.pages.map((page) => page.index),
    Array.from({ length: total }, (_, index) => index + 1),
  );
});

test("上限可调，按更小的上限会切出更多张", () => {
  const long = Array.from(
    { length: 60 },
    (_, index) => `第 ${index} 段正文。`,
  ).join("\n\n");
  const small = layoutShareCard(conversation(long), labels, measure, {
    maxPageHeight: 900,
  });
  assert.ok(small.pages.length > 1);
  for (const page of small.pages) assert.ok(page.height <= 900);
});
