test("markdown 解析出标题、段落、代码块、列表、表格、公式、分割线", () => {
  const blocks = markdownToShareBlocks(
    [
      "# 结论",
      "",
      "同比 **增长** 了 `12%`，见 [明细](https://example.com)。",
      "",
      "$$E = mc^2$$",
      "",
      "行内公式 $a^2+b^2$ 也要认。",
      "",
      "```python",
      "print('hi')",
      "```",
      "",
      "1. 先算总量",
      "2. 再算同比",
      "   - 去年同期",
      "",
      "| 月份 | 收入 |",
      "| --- | --- |",
      "| 1 月 | 100 |",
      "",
      "---",
      "",
      "> 数据来自用户上传的 xlsx。",
    ].join("\n"),
  );
  const kinds = blocks.map((block) => block.type);
  assert.ok(kinds.includes("heading"));
  assert.ok(kinds.includes("code"));
  assert.ok(kinds.includes("list"));
  assert.ok(kinds.includes("table"));
  assert.ok(kinds.includes("rule"));
  assert.ok(kinds.includes("quote"));

  const displayMath = blocks.find((block) => block.type === "math");
  assert.equal(displayMath.tex, "E = mc^2");

  const inlineMathParagraph = blocks.find(
    (block) =>
      block.type === "paragraph" &&
      block.inlines.some((inline) => inline.type === "math"),
  );
  assert.equal(
    inlineMathParagraph.inlines.find((inline) => inline.type === "math").tex,
    "a^2+b^2",
  );

  const code = blocks.find((block) => block.type === "code");
  assert.equal(code.lang, "python");
  assert.deepEqual(code.lines, ["print('hi')"]);

  const list = blocks.find((block) => block.type === "list");
  assert.equal(list.ordered, true);
  assert.equal(list.items[0].index, 1);
  assert.equal(list.items[2].depth, 1);

  const table = blocks.find((block) => block.type === "table");
  assert.deepEqual(table.header.map(inlinesToPlainText), ["月份", "收入"]);
  assert.deepEqual(table.rows[0].map(inlinesToPlainText), ["1 月", "100"]);

  const paragraph = blocks.find(
    (block) =>
      block.type === "paragraph" &&
      inlinesToPlainText(block.inlines).includes("同比"),
  );
  assert.ok(paragraph.inlines.some((inline) => inline.bold));
  assert.ok(paragraph.inlines.some((inline) => inline.code));
  assert.ok(paragraph.inlines.some((inline) => inline.href));
});

test("围栏代码块里的 $$ 不会被当成公式切开", () => {
  const blocks = markdownToShareBlocks(
    ["```bash", "echo $$ && echo done", "```"].join("\n"),
  );
  assert.equal(blocks.length, 1);
  assert.equal(blocks[0].type, "code");
  assert.equal(blocks[0].lines[0], "echo $$ && echo done");
});

