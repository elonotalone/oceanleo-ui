import assert from "node:assert/strict";
import test from "node:test";

import {
  markdownToShareBlocks,
  inlinesToPlainText,
} from "../src/shell/share/share-blocks.ts";
import {
  SHARE_CARD_WIDTH,
  SHARE_MAX_PAGE_HEIGHT,
  SHARE_MIN_TABLE_FONT,
  layoutShareCard,
  planTableColumns,
} from "../src/shell/share/share-layout.ts";

/** 决定性测量器：宽度只跟字数与字号有关，不需要浏览器。 */
const measure = {
  measureText: (text, font) => String(text).length * font.size * 0.6,
  measureMath: (tex, display) => ({
    width: Math.min(600, tex.length * 9),
    height: display ? 46 : 20,
  }),
  imageSize: () => ({ width: 1200, height: 800 }),
};

const measureWithoutMath = {
  measureText: measure.measureText,
  imageSize: measure.imageSize,
};

const labels = {
  title: "同比分析",
  subtitle: "2026-08-20",
  brand: "Generated by OceanLeo",
  tagline: "在 OceanLeo 上生成图片、文档、网站和小工具。",
  linkText: "https://oceanleo.com/share/abc123",
  tableTruncated: "完整表格见原对话",
  pageIndicator: "{index}/{total}",
};

function textItems(page) {
  return page.items.filter((item) => item.kind === "text");
}

function allTexts(page) {
  return textItems(page).map((item) => item.text);
}

