function conversation(markdown) {
  return [
    { role: "user", speaker: "我", blocks: markdownToShareBlocks("帮我算个同比") },
    {
      role: "assistant",
      speaker: "OceanLeo",
      blocks: markdownToShareBlocks(markdown),
    },
  ];
}

test("普通会话排成一张 750px 宽的卡片，含页眉页脚与二维码", () => {
  const qr = [
    [true, false, true],
    [false, true, false],
    [true, false, true],
  ];
  const result = layoutShareCard(
    conversation("# 结论\n\n同比增长 12%。\n\n```py\nprint(1)\n```"),
    labels,
    measure,
    { qrModules: qr },
  );
  assert.equal(result.width, SHARE_CARD_WIDTH);
  assert.equal(result.pages.length, 1);
  const page = result.pages[0];
  assert.equal(page.width, SHARE_CARD_WIDTH);
  assert.ok(page.height <= SHARE_MAX_PAGE_HEIGHT);
  assert.ok(allTexts(page).includes("同比分析"));
  assert.ok(allTexts(page).includes("Generated by OceanLeo"));
  assert.equal(page.items.filter((item) => item.kind === "qr").length, 1);
  // 单页时不出现 1/1 页码
  assert.ok(!allTexts(page).includes("1/1"));
});

test("代码块有等宽字体与深色背景，列表有缩进，表格有边框", () => {
  const result = layoutShareCard(
    conversation(
      [
        "```js",
        "const a = 1;",
        "```",
        "",
        "- 第一条",
        "- 第二条",
        "",
        "| a | b |",
        "| --- | --- |",
        "| 1 | 2 |",
      ].join("\n"),
    ),
    labels,
    measure,
  );
  const page = result.pages[0];
  const monoText = textItems(page).filter((item) => item.font.mono);
  assert.ok(monoText.some((item) => item.text === "const a = 1;"));
  assert.ok(
    page.items.some(
      (item) => item.kind === "rect" && item.fill === "#1c1917",
    ),
    "代码块要有深色背景",
  );
  const markers = allTexts(page).filter((text) => text === "•");
  assert.equal(markers.length, 2);
  const bulletX = textItems(page).find((item) => item.text === "第一条").x;
  const markerX = textItems(page).find((item) => item.text === "•").x;
  assert.ok(bulletX > markerX, "列表文字要缩进到项目符号右边");
  assert.ok(
    page.items.some(
      (item) => item.kind === "rect" && item.stroke === "#e7e5e4",
    ),
    "表格要有边框",
  );
});

test("公式走注入的渲染器；渲染器缺席时退回等宽文本且被计数", () => {
  const withMath = layoutShareCard(
    conversation("$$\\int_0^1 x dx$$ 与 $x^2$ 同时出现。"),
    labels,
    measure,
  );
  const mathItems = withMath.pages[0].items.filter(
    (item) => item.kind === "math",
  );
  assert.equal(withMath.fallbackFormulas, 0);
  assert.ok(mathItems.some((item) => item.display === true));
  assert.ok(mathItems.some((item) => item.display === false));

  const withoutMath = layoutShareCard(
    conversation("$$\\int_0^1 x dx$$ 与 $x^2$ 同时出现。"),
    labels,
    measureWithoutMath,
  );
  assert.equal(
    withoutMath.pages[0].items.filter((item) => item.kind === "math").length,
    0,
  );
  assert.ok(withoutMath.fallbackFormulas >= 2);
});

