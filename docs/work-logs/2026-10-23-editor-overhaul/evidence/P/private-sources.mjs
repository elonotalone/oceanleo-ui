import fs from 'node:fs';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
const token = fs.readFileSync(0, 'utf8').trim();
const api = 'https://api.dev.oceanleo.com';
const headers = { Authorization: `Bearer ${token}` };
const bytes = fs.readFileSync(new URL('../../harness/fixtures/sample.mp3', import.meta.url));
const file = new File([bytes], 'source.mp3', { type: 'audio/mpeg' });
const body = new FormData(); body.append('file', file);
const upload = await fetch(`${api}/v1/editor-sources`, { method: 'POST', headers, body });
assert.equal(upload.status, 200);
const { file: receipt } = await upload.json();
assert.equal(receipt.digest, createHash('sha256').update(bytes).digest('hex'));
const url = new URL(`${api}/v1/editor-sources/${receipt.digest}`);
url.searchParams.set('key', receipt.key); url.searchParams.set('size', receipt.bytes); url.searchParams.set('mime', receipt.mime);
const read = await fetch(url, { headers }); assert.equal(read.status, 200);
assert.deepEqual(Buffer.from(await read.arrayBuffer()), bytes);
const anonymous = await fetch(url); assert.equal(anonymous.status, 401);
const other = new URL(url); other.searchParams.set('key', receipt.key.replace(/^u\/[^/]+\//, 'u/bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb/'));
const refused = await fetch(other, { headers }); assert.equal(refused.status, 404);
console.log(JSON.stringify({ upload: upload.status, read: read.status, unauthenticated: anonymous.status, wrongOwner: refused.status, mime: receipt.mime, byteSize: receipt.bytes, exactBytes: true }));
