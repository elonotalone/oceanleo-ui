import fs from 'node:fs';
import assert from 'node:assert/strict';
const token = fs.readFileSync(0, 'utf8').trim();
const api = 'https://api.dev.oceanleo.com';
const headers = { Authorization: `Bearer ${token}` };
const data = { version: 1, rootId: 'codex-private-draft-probe', baseRevisionId: 'probe', schema: 'acceptance.v1', editRevision: 1, savedAt: new Date().toISOString(), data: { text: '保存重开验收' } };
const file = new File([JSON.stringify(data)], 'working-document.json', { type: 'application/json' });
const body = new FormData(); body.append('file', file);
const upload = await fetch(`${api}/v1/editor-drafts`, { method: 'POST', headers, body });
assert.equal(upload.status, 200, 'private draft upload');
const { file: receipt } = await upload.json();
const url = new URL(`${api}/v1/editor-drafts/${receipt.digest}`);
url.searchParams.set('key', receipt.key); url.searchParams.set('size', receipt.bytes);
const read = await fetch(url, { headers });
assert.equal(read.status, 200); assert.deepEqual(await read.json(), data);
assert.equal(read.headers.get('cache-control'), 'private, no-store');
const unauthenticated = await fetch(url); assert.equal(unauthenticated.status, 401);
const other = new URL(url); other.searchParams.set('key', receipt.key.replace(/^u\/[^/]+\//, 'u/bbbbbbbb-bbbb-4bbb-8bbb-bbbbbbbbbbbb/'));
const refused = await fetch(other, { headers }); assert.equal(refused.status, 404);
console.log(JSON.stringify({ upload: upload.status, read: read.status, unauthenticated: unauthenticated.status, wrongOwner: refused.status, byteSize: receipt.bytes, contentMatches: true }));
