import assert from "node:assert/strict";
import { OWN_FORK, canvasInfo, openCanvas } from "./_w16-lib.mjs";

export default async function ({ page, log, shot, helpers }) {
  let commits = 0;
  page.on("response", response => {
    if (response.request().method() === "POST" && /\/v1\/artifacts\/[^/]+\/revisions$/.test(new URL(response.url()).pathname) && response.ok()) commits++;
  });
  await openCanvas(page, helpers, log, OWN_FORK);
  const before = await canvasInfo(page);
  const nodesAre = count => page.waitForFunction(expected => document.querySelectorAll("[data-testid=video-canvas-node]").length === expected, count, { timeout: 5000 });
  const node = id => page.locator(`[data-testid=video-canvas-node][data-node-id="${id}"]`);
  const button = id => page.locator(`[data-selection-control-id="${id}"] button`).first();
  await page.locator(".react-flow__pane").click({ position: { x: 50, y: 80 } });
  await page.getByRole("button", { name: /^(Add node|加节点)$/ }).click();
  await page.locator('[data-testid=video-canvas-add-node][data-node-kind="script"]').click();
  const added = (await canvasInfo(page)).nodes.find(value => !before.nodes.some(old => old.id === value.id));
  assert.ok(added);
  await node(added.id).click({ force: true });
  await button("selection-inspector-video-node-params").click();
  const fields = page.locator("[data-selection-inspector] textarea");
  await fields.nth(0).fill("W16 controls verified");
  await fields.nth(0).blur();
  await fields.nth(1).fill("Visible storyboard copy");
  await fields.nth(1).blur();
  await page.keyboard.press("Escape");
  assert.match(await node(added.id).textContent(), /Visible storyboard copy/);
  await page.getByRole("button", { name: /^(Position and size|位置与尺寸)$/ }).click();
  const number = page.locator("[data-selection-inspector] input[type=number]").first();
  const x = Number(await number.inputValue()) + 70;
  await number.fill(String(x));
  await number.press("Enter");
  await number.blur();
  await page.keyboard.press("Escape");
  assert.match((await canvasInfo(page)).nodes.find(value => value.id === added.id).rect, new RegExp(`^${x}px`));
  await button("lock").click();
  assert.equal(await page.locator('[data-selection-control-id="delete"]').count(), 0);
  await button("lock").click();
  await button("duplicate").click();
  await nodesAre(before.nodes.length + 2);
  assert.equal((await canvasInfo(page)).nodes.length, before.nodes.length + 2);
  await button("delete").click();
  await nodesAre(before.nodes.length + 1);
  assert.equal((await canvasInfo(page)).nodes.length, before.nodes.length + 1);
  await page.getByRole("button", { name: /^(Undo|撤销)$/ }).click();
  await nodesAre(before.nodes.length + 2);
  assert.equal((await canvasInfo(page)).nodes.length, before.nodes.length + 2);
  await page.getByRole("button", { name: /^(Redo|重做)$/ }).click();
  await nodesAre(before.nodes.length + 1);
  assert.equal((await canvasInfo(page)).nodes.length, before.nodes.length + 1);
  await page.locator(".react-flow__controls-fitview").click();
  await page.waitForTimeout(350);
  const src = page.locator(`.react-flow__node[data-id="${added.id}"] .react-flow__handle.source`);
  const dst = page.locator('.react-flow__node[data-id="brief"] .react-flow__handle.target');
  const a = await src.boundingBox();
  const b = await dst.boundingBox();
  const beforeConnectCommits = commits;
  await page.mouse.move(a.x + a.width / 2, a.y + a.height / 2);
  await page.mouse.down();
  await page.mouse.move(b.x + b.width / 2, b.y + b.height / 2, { steps: 15 });
  await page.mouse.up();
  await page.waitForFunction(expected => document.querySelectorAll(".react-flow__edge").length === expected, before.edges + 1, { timeout: 5000 });
  assert.equal((await canvasInfo(page)).edges, before.edges + 1);
  await page.locator(".react-flow__edge").last().dispatchEvent("click");
  await button("delete").click();
  await page.waitForFunction(expected => document.querySelectorAll(".react-flow__edge").length === expected, before.edges, { timeout: 5000 });
  assert.equal((await canvasInfo(page)).edges, before.edges);
  await page.getByRole("button", { name: /^(Undo|撤销)$/ }).click();
  await page.waitForFunction(expected => document.querySelectorAll(".react-flow__edge").length === expected, before.edges + 1, { timeout: 5000 });
  assert.equal((await canvasInfo(page)).edges, before.edges + 1);
  for (let n = 0; n < 180 && commits === beforeConnectCommits; n++) await page.waitForTimeout(500);
  assert.ok(commits > beforeConnectCommits);
  await helpers.waitSaved(page, { timeout: 90000 });
  await shot("01-controls-saved");
  await page.reload({ waitUntil: "domcontentloaded" });
  await openCanvas(page, helpers, log, OWN_FORK);
  assert.match(await node(added.id).textContent(), /W16 controls verified/);
  assert.match(await node(added.id).textContent(), /Visible storyboard copy/);
  assert.equal((await canvasInfo(page)).edges, before.edges + 1);
  log("PASS", "add/parameters/position/lock/duplicate/delete/undo/redo/connect persisted");
  await shot("02-controls-reopened");
}
