#!/usr/bin/env node
/**
 * 生成 `geo/ne-110m-land.ts` 与 `geo/plan-sheet.ts` —— 地图三件第一屏的内置底图。
 *
 * 输入是 Natural Earth 5.1.1 的 `ne_110m_admin_0_countries.geojson`（公有领域，PDM）。
 * 本机取值：
 *   /opt/cursor-workspaces/oceandino/scratch/s5-w9-natural-earth/natural-earth-vector/geojson/
 * 上游：https://github.com/nvkelso/natural-earth-vector
 *
 * 三步：属性只留中文名与 ISO 二字码；经纬度四舍五入到 2 位小数（1:110m 档上约
 * 1.1 km，远细于该档的制图精度）；环上相邻重合点去掉、首尾闭合。产物是一段
 * UTF-8 JSON 文本，连同它自己的 sha256 与字节数一起写成 TS 模块，运行时不落
 * 网络、不进货架、不进 artifact_revisions。
 *
 * 用法：node src/shell/plugin-initial-states/data/build-basemap.mjs [源 geojson 路径]
 */

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const DEFAULT_SOURCE =
  "/opt/cursor-workspaces/oceandino/scratch/s5-w9-natural-earth/natural-earth-vector/geojson/ne_110m_admin_0_countries.geojson";
const DECIMALS = 2;
const here = dirname(fileURLToPath(import.meta.url));

function roundRing(ring) {
  const factor = 10 ** DECIMALS;
  const out = [];
  let previous = null;
  for (const [lon, lat] of ring) {
    const point = [Math.round(lon * factor) / factor, Math.round(lat * factor) / factor];
    if (previous && point[0] === previous[0] && point[1] === previous[1]) continue;
    out.push(point);
    previous = point;
  }
  if (out.length >= 2) {
    const [first] = out;
    const last = out[out.length - 1];
    if (first[0] !== last[0] || first[1] !== last[1]) out.push([first[0], first[1]]);
  }
  // 少于 4 点的环围不出面积，丢掉比留一条退化边好。
  return out.length >= 4 ? out : null;
}

/**
 * 户型标注的底图不来自任何上游：它是一张**空的量图纸**——1 m 网格加一圈图纸边框，
 * 上面没有任何房间。geo-map 内核吃经纬度，所以图纸用「1 m = 赤道 1 米对应的度数」
 * 换算到原点附近的一小块地方，纯粹当作平面直角坐标用。
 */
const METRE_IN_DEGREES = 1 / 111319.4907932736;
const PLAN_WIDTH_M = 24;
const PLAN_HEIGHT_M = 18;

function planMetres(x, y) {
  const round = (value) => Number(value.toFixed(10));
  return [round(x * METRE_IN_DEGREES), round(y * METRE_IN_DEGREES)];
}

function buildPlanSheet() {
  const halfWidth = PLAN_WIDTH_M / 2;
  const halfHeight = PLAN_HEIGHT_M / 2;
  const features = [];
  for (let x = -halfWidth; x <= halfWidth; x += 1) {
    features.push({
      type: "Feature",
      properties: { role: "grid", axis: "x", metre: x },
      geometry: {
        type: "LineString",
        coordinates: [planMetres(x, -halfHeight), planMetres(x, halfHeight)],
      },
    });
  }
  for (let y = -halfHeight; y <= halfHeight; y += 1) {
    features.push({
      type: "Feature",
      properties: { role: "grid", axis: "y", metre: y },
      geometry: {
        type: "LineString",
        coordinates: [planMetres(-halfWidth, y), planMetres(halfWidth, y)],
      },
    });
  }
  const border = {
    type: "Feature",
    properties: {
      role: "sheet",
      widthMetres: PLAN_WIDTH_M,
      heightMetres: PLAN_HEIGHT_M,
    },
    geometry: {
      type: "Polygon",
      coordinates: [
        [
          planMetres(-halfWidth, -halfHeight),
          planMetres(halfWidth, -halfHeight),
          planMetres(halfWidth, halfHeight),
          planMetres(-halfWidth, halfHeight),
          planMetres(-halfWidth, -halfHeight),
        ],
      ],
    },
  };
  return {
    grid: { type: "FeatureCollection", features },
    sheet: { type: "FeatureCollection", features: [border] },
  };
}

const digest = (text) => createHash("sha256").update(text, "utf8").digest("hex");

function emitPayload(fileName, banner, entries) {
  const body = entries
    .map((entry) => `export const ${entry.name} = ${JSON.stringify(entry.json)};`)
    .join("\n\n");
  const target = join(here, "geo", fileName);
  writeFileSync(target, `${banner}\n\n${body}\n`, "utf8");
  process.stdout.write(`${target}\n`);
}

function emitManifest(records) {
  const rows = records
    .map(
      (record) => `  {
    path: "${record.path}",
    sha256: "${digest(record.json)}",
    byteSize: ${Buffer.byteLength(record.json, "utf8")},
    featureCount: ${record.featureCount},
    mediaType: "application/geo+json",
    licenseCode: "${record.licenseCode}",
    attribution: "${record.attribution}",
  },`,
    )
    .join("\n");
  const module = `/**
 * GENERATED by ../build-basemap.mjs —— 不要手改。
 *
 * 内置底图的清单：路径、真实 sha256、真实字节数。字节本身在同目录的 payload 模块里，
 * 由 \`../index.ts\` 动态 import 取，所以清单可以被静态引用而不把几十万字节拖进首包。
 * 这些件是**随包发布的内置数据，不是素材**：不进货架、不进 artifact_revisions、没有份数。
 */

export interface BuiltInGeoAsset {
  path: string;
  sha256: string;
  byteSize: number;
  featureCount: number;
  mediaType: "application/geo+json";
  licenseCode: "PDM" | "CC0";
  attribution: string;
}

export const BUILT_IN_GEO_ASSETS: readonly BuiltInGeoAsset[] = Object.freeze([
${rows}
]);

export const PLAN_METRE_IN_DEGREES = ${METRE_IN_DEGREES};
export const PLAN_WIDTH_METRES = ${PLAN_WIDTH_M};
export const PLAN_HEIGHT_METRES = ${PLAN_HEIGHT_M};
`;
  const target = join(here, "geo", "manifest.ts");
  writeFileSync(target, module, "utf8");
  process.stdout.write(`${target}\n`);
  for (const record of records) {
    process.stdout.write(
      `  ${record.path} bytes=${Buffer.byteLength(record.json, "utf8")} features=${record.featureCount} sha256=${digest(record.json)}\n`,
    );
  }
}

function main() {
  const { grid, sheet } = buildPlanSheet();
  const gridJson = JSON.stringify(grid);
  const sheetJson = JSON.stringify(sheet);
  emitPayload(
    "plan-sheet.ts",
    `/**
 * GENERATED by ../build-basemap.mjs —— 不要手改。
 *
 * 户型标注的空量图纸：${PLAN_WIDTH_M} m × ${PLAN_HEIGHT_M} m，1 m 网格，上面没有任何房间。
 * 1 m = ${METRE_IN_DEGREES} 度（赤道），图纸中心落在经纬度原点。
 * OceanLeo 自制，CC0。
 */`,
    [
      { name: "PLAN_GRID_GEOJSON", json: gridJson },
      { name: "PLAN_SHEET_GEOJSON", json: sheetJson },
    ],
  );

  const sourcePath = process.argv[2] || DEFAULT_SOURCE;
  const source = JSON.parse(readFileSync(sourcePath, "utf8"));
  const features = [];
  for (const feature of source.features) {
    const geometry = feature.geometry;
    const polygons =
      geometry.type === "Polygon" ? [geometry.coordinates] : geometry.coordinates;
    const kept = [];
    for (const polygon of polygons) {
      const rings = [];
      for (const ring of polygon) {
        const rounded = roundRing(ring);
        if (rounded) rings.push(rounded);
      }
      if (rings.length) kept.push(rings);
    }
    if (!kept.length) continue;
    features.push({
      type: "Feature",
      properties: {
        name: feature.properties.NAME_ZH || feature.properties.NAME,
        code: feature.properties.ISO_A2,
      },
      geometry:
        kept.length === 1
          ? { type: "Polygon", coordinates: kept[0] }
          : { type: "MultiPolygon", coordinates: kept },
    });
  }
  const json = JSON.stringify({ type: "FeatureCollection", features });
  emitPayload(
    "ne-110m-land.ts",
    `/**
 * GENERATED by ../build-basemap.mjs —— 不要手改。重生成见该脚本头注释。
 *
 * Natural Earth 5.1.1 \`ne_110m_admin_0_countries\`，属性裁到中文名 + ISO 二字码，
 * 经纬度 ${DECIMALS} 位小数。许可 PDM（公有领域标记），**不是 CC0**。
 * 要素 ${features.length} 个。
 */`,
    [{ name: "NE_110M_LAND_GEOJSON", json }],
  );

  emitManifest([
    {
      path: "geo/ne-110m-land.geojson",
      json,
      featureCount: features.length,
      licenseCode: "PDM",
      attribution: "Natural Earth 5.1.1 admin-0 countries，1:110m，公有领域（PDM）",
    },
    {
      path: "plan/grid-1m.geojson",
      json: gridJson,
      featureCount: grid.features.length,
      licenseCode: "CC0",
      attribution: `OceanLeo 量图纸 1 m 网格（${PLAN_WIDTH_M} m × ${PLAN_HEIGHT_M} m）`,
    },
    {
      path: "plan/sheet.geojson",
      json: sheetJson,
      featureCount: sheet.features.length,
      licenseCode: "CC0",
      attribution: `OceanLeo 量图纸边框（${PLAN_WIDTH_M} m × ${PLAN_HEIGHT_M} m）`,
    },
  ]);
}

main();
