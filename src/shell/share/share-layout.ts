function headerRows(
  labels: ShareCardLabels,
  context: BlockContext,
): { rows: FlowRow[]; height: number } {
  const rows: FlowRow[] = [];
  const titleLines = layoutInlines(
    [{ type: "text", text: labels.title || labels.brand, bold: true }],
    {
      baseFont: sans(24, 700),
      color: SHARE_COLORS.text,
      maxWidth: context.width,
      measure: context.measure,
      lineHeightRatio: 1.4,
    },
  ).slice(0, 3);
  rows.push(...linesToRows(titleLines));
  if (labels.subtitle) {
    rows.push(spacer(6));
    rows.push(
      ...linesToRows(
        layoutInlines([{ type: "text", text: labels.subtitle }], {
          baseFont: sans(13),
          color: SHARE_COLORS.faint,
          maxWidth: context.width,
          measure: context.measure,
        }),
      ),
    );
  }
  rows.push(spacer(14));
  rows.push({
    height: 1,
    render: (x, y) => [
      {
        kind: "line",
        x,
        y,
        width: context.width,
        color: SHARE_COLORS.rule,
        thickness: 1,
      },
    ],
  });
  rows.push(spacer(20));
  return { rows, height: rows.reduce((sum, row) => sum + row.height, 0) };
}

function footerItems(
  labels: ShareCardLabels,
  context: BlockContext,
  qrModules: readonly (readonly boolean[])[] | null,
  x: number,
  y: number,
  pageIndex: number,
  pageTotal: number,
): ShareDrawItem[] {
  const items: ShareDrawItem[] = [
    {
      kind: "line",
      x,
      y,
      width: context.width,
      color: SHARE_COLORS.rule,
      thickness: 1,
    },
  ];
  const top = y + 20;
  const hasQr = Boolean(qrModules && qrModules.length);
  const textWidth = context.width - (hasQr ? QR_SIZE + 20 : 0);
  items.push({
    kind: "text",
    x,
    y: top,
    text: labels.brand,
    font: sans(15, 700),
    color: SHARE_COLORS.text,
  });
  const taglineLines = layoutInlines(
    [{ type: "text", text: labels.tagline }],
    {
      baseFont: sans(12.5),
      color: SHARE_COLORS.muted,
      maxWidth: textWidth,
      measure: context.measure,
      lineHeightRatio: 1.5,
    },
  ).slice(0, 2);
  let cursor = top + 24;
  for (const line of taglineLines) {
    items.push(...shift(line.items, x, cursor));
    cursor += line.height;
  }
  if (labels.linkText) {
    items.push({
      kind: "text",
      x,
      y: cursor + 4,
      text: clipToWidth(labels.linkText, textWidth, sans(11.5), context.measure),
      font: sans(11.5),
      color: SHARE_COLORS.faint,
    });
  }
  if (hasQr && qrModules) {
    items.push({
      kind: "qr",
      x: x + context.width - QR_SIZE,
      y: top - 4,
      size: QR_SIZE,
      modules: qrModules,
    });
  }
  if (pageTotal > 1) {
    items.push({
      kind: "text",
      x: x + context.width,
      y: y + 4,
      text: labels.pageIndicator
        .replace("{index}", String(pageIndex))
        .replace("{total}", String(pageTotal)),
      font: sans(11.5, 600),
      color: SHARE_COLORS.faint,
      align: "right",
    });
  }
  return items;
}

const FOOTER_HEIGHT = 108;

// ---------------------------------------------------------------------------
// 主入口
// ---------------------------------------------------------------------------

export function layoutShareCard(
  messages: readonly ShareCardMessage[],
  labels: ShareCardLabels,
  measure: ShareMeasureContext,
  options: ShareLayoutOptions = {},
): ShareLayoutResult {
  const width = options.width ?? SHARE_CARD_WIDTH;
  const maxPageHeight = options.maxPageHeight ?? SHARE_MAX_PAGE_HEIGHT;
  const contentLeft = PAGE_MARGIN + CARD_PADDING;
  const contentWidth = width - contentLeft * 2;
  let truncatedTables = 0;
  let fallbackFormulas = 0;

  const context: BlockContext = {
    width: contentWidth,
    measure,
    labels,
    onTruncatedTable: () => {
      truncatedTables += 1;
    },
    onFallbackFormula: () => {
      fallbackFormulas += 1;
    },
  };

  const header = headerRows(labels, context);
  const chrome = PAGE_MARGIN * 2 + CARD_PADDING * 2 + FOOTER_HEIGHT;
  const firstPageBudget = maxPageHeight - chrome - header.height;
  const otherPageBudget = maxPageHeight - chrome;

  // --- 消息 → section --------------------------------------------------
  const sections: FlowSection[] = [];
  for (const message of messages) {
    const isUser = message.role === "user";
    const bubbleContentWidth = isUser
      ? Math.round(contentWidth * USER_BUBBLE_MAX_RATIO) - BUBBLE_PADDING_X * 2
      : contentWidth;
    const sectionContext: BlockContext = {
      ...context,
      width: Math.max(120, bubbleContentWidth),
    };
    const bodyRows: FlowRow[] = [];
    for (const block of message.blocks) {
      const rows = blockRows(
        block,
        sectionContext,
        otherPageBudget - BUBBLE_PADDING_Y * 2,
      );
      if (bodyRows.length && rows.length) bodyRows.push(spacer(BLOCK_GAP));
      bodyRows.push(...rows);
    }
    if (!bodyRows.length) continue;

    if (isUser) {
      // 气泡宽度取实际最宽的一行，右对齐——不是永远铺满 78%。
      const used = Math.max(
        ...bodyRows.map((row) =>
          Math.max(
            0,
            ...row
              .render(0, 0)
              .map((item) =>
                item.kind === "text"
                  ? item.x + measure.measureText(item.text, item.font)
                  : "width" in item
                    ? item.x + item.width
                    : 0,
              ),
          ),
        ),
        120,
      );
      const bubbleWidth = Math.min(
        Math.round(contentWidth * USER_BUBBLE_MAX_RATIO),
        Math.ceil(used) + BUBBLE_PADDING_X * 2,
      );
      sections.push({
        bubble: true,
        x: contentLeft + contentWidth - bubbleWidth,
        width: bubbleWidth,
        rows: [
          spacer(BUBBLE_PADDING_Y),
          ...bodyRows.map((row) => ({
            height: row.height,
            render: (x: number, y: number) =>
              row.render(x + BUBBLE_PADDING_X, y),
          })),
          spacer(BUBBLE_PADDING_Y),
        ],
      });
    } else {
      const speakerFont = sans(12, 600);
      const speakerRows: FlowRow[] = message.speaker
        ? [
            {
              height: 22,
              render: (x, y) => [
                {
                  kind: "text",
                  x,
                  y,
                  text: message.speaker,
                  font: speakerFont,
                  color: SHARE_COLORS.faint,
                },
              ],
            },
          ]
        : [];
      sections.push({
        bubble: false,
        x: contentLeft,
        width: contentWidth,
        rows: [...speakerRows, ...bodyRows],
      });
    }
    sections.push({
      bubble: false,
      x: contentLeft,
      width: contentWidth,
      rows: [spacer(SECTION_GAP)],
    });
  }

  // --- 分页 -------------------------------------------------------------
  interface PlacedRow {
    section: FlowSection;
    row: FlowRow;
  }
  const flat: PlacedRow[] = [];
  for (const section of sections) {
    for (const row of section.rows) flat.push({ section, row });
  }

  const pageBuckets: PlacedRow[][] = [];
  let bucket: PlacedRow[] = [];
  let used = 0;
  let budget = firstPageBudget;
  for (const placed of flat) {
    const height = Math.min(placed.row.height, budget);
    if (used > 0 && used + height > budget) {
      pageBuckets.push(bucket);
      bucket = [];
      used = 0;
      budget = otherPageBudget;
    }
    bucket.push(placed);
    used += height;
  }
  if (bucket.length || !pageBuckets.length) pageBuckets.push(bucket);

  const pageTotal = pageBuckets.length;
  const pages: SharePage[] = pageBuckets.map((rows, position) => {
    const pageIndex = position + 1;
    const contentTop =
      PAGE_MARGIN + CARD_PADDING + (pageIndex === 1 ? header.height : 0);
    const bodyHeight = rows.reduce((sum, placed) => sum + placed.row.height, 0);
    const pageHeight = Math.max(
      320,
      Math.round(contentTop + bodyHeight + FOOTER_HEIGHT + CARD_PADDING + PAGE_MARGIN),
    );
    const items: ShareDrawItem[] = [
      {
        kind: "rect",
        x: 0,
        y: 0,
        width,
        height: pageHeight,
        fill: SHARE_COLORS.pageBackground,
      },
      {
        kind: "rect",
        x: PAGE_MARGIN,
        y: PAGE_MARGIN,
        width: width - PAGE_MARGIN * 2,
        height: pageHeight - PAGE_MARGIN * 2,
        fill: SHARE_COLORS.card,
        stroke: SHARE_COLORS.cardBorder,
        lineWidth: 1,
        radius: 22,
      },
    ];
    if (pageIndex === 1) {
      let cursor = PAGE_MARGIN + CARD_PADDING;
      for (const row of header.rows) {
        items.push(...row.render(contentLeft, cursor));
        cursor += row.height;
      }
    }
    // 气泡底色：一个 section 可能被切到两页，底色按**本页落到的行范围**单独补一块。
    // 必须先于正文入队，否则会盖住字。
    let cursor = contentTop;
    let runSection: FlowSection | null = null;
    let runTop = cursor;
    const closeBubble = (bottom: number) => {
      if (!runSection?.bubble) return;
      items.push({
        kind: "rect",
        x: runSection.x,
        y: runTop,
        width: runSection.width,
        height: Math.max(1, bottom - runTop),
        fill: SHARE_COLORS.userBubble,
        radius: 18,
      });
    };
    for (const placed of rows) {
      if (placed.section !== runSection) {
        closeBubble(cursor);
        runSection = placed.section;
        runTop = cursor;
      }
      cursor += placed.row.height;
    }
    closeBubble(cursor);

    cursor = contentTop;
    for (const placed of rows) {
      items.push(...placed.row.render(placed.section.x, cursor));
      cursor += placed.row.height;
    }
    items.push(
      ...footerItems(
        labels,
        context,
        options.qrModules ?? null,
        contentLeft,
        pageHeight - PAGE_MARGIN - CARD_PADDING - FOOTER_HEIGHT,
        pageIndex,
        pageTotal,
      ),
    );
    return { index: pageIndex, width, height: pageHeight, items };
  });

  return { width, pages, truncatedTables, fallbackFormulas };
}
