interface FlowRow {
  height: number;
  /** 相对本行左上角作画；分页后统一平移。 */
  render: (x: number, y: number) => ShareDrawItem[];
}

interface FlowSection {
  /** 用户气泡要底色；助手正文不要。 */
  bubble: boolean;
  x: number;
  width: number;
  rows: FlowRow[];
}

function shift(items: ShareDrawItem[], dx: number, dy: number): ShareDrawItem[] {
  return items.map((item) => {
    if (item.kind === "line") return { ...item, x: item.x + dx, y: item.y + dy };
    return { ...item, x: item.x + dx, y: item.y + dy } as ShareDrawItem;
  });
}

function spacer(height: number): FlowRow {
  return { height, render: () => [] };
}

function linesToRows(lines: LaidLine[], offsetX = 0): FlowRow[] {
  return lines.map((line) => ({
    height: line.height,
    render: (x: number, y: number) => shift(line.items, x + offsetX, y),
  }));
}

