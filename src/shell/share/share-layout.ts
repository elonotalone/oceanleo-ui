interface BlockContext {
  width: number;
  measure: ShareMeasureContext;
  labels: ShareCardLabels;
  onTruncatedTable: () => void;
  onFallbackFormula: () => void;
}

const HEADING_SIZE = [26, 22, 19, 17, 16, 15];

function headingRows(
  block: Extract<ShareBlock, { type: "heading" }>,
  context: BlockContext,
): FlowRow[] {
  const size = HEADING_SIZE[Math.min(5, block.level - 1)];
  const lines = layoutInlines(block.inlines, {
    baseFont: sans(size, 700),
    color: SHARE_COLORS.text,
    maxWidth: context.width,
    measure: context.measure,
    lineHeightRatio: 1.45,
    onFallbackFormula: context.onFallbackFormula,
  });
  return [spacer(block.level <= 2 ? 12 : 8), ...linesToRows(lines), spacer(4)];
}

function paragraphRows(
  inlines: readonly ShareInline[],
  context: BlockContext,
  font = sans(16),
): FlowRow[] {
  const lines = layoutInlines(inlines, {
    baseFont: font,
    color: SHARE_COLORS.text,
    maxWidth: context.width,
    measure: context.measure,
    onFallbackFormula: context.onFallbackFormula,
  });
  return linesToRows(lines);
}

function quoteRows(
  block: Extract<ShareBlock, { type: "quote" }>,
  context: BlockContext,
): FlowRow[] {
  const inset = 16;
  const lines = layoutInlines(block.inlines, {
    baseFont: sans(15, 400, true),
    color: SHARE_COLORS.muted,
    maxWidth: context.width - inset,
    measure: context.measure,
    onFallbackFormula: context.onFallbackFormula,
  });
  return lines.map((line) => ({
    height: line.height,
    render: (x: number, y: number) => [
      {
        kind: "rect" as const,
        x,
        y,
        width: 3,
        height: line.height,
        fill: SHARE_COLORS.quoteBar,
      },
      ...shift(line.items, x + inset, y),
    ],
  }));
}

function listRows(
  block: Extract<ShareBlock, { type: "list" }>,
  context: BlockContext,
): FlowRow[] {
  const rows: FlowRow[] = [];
  const font = sans(16);
  const markerFont = sans(15, 600);
  for (const item of block.items) {
    const indent = 22 * item.depth;
    const marker = listMarker(item);
    const markerWidth = Math.max(
      22,
      context.measure.measureText(marker, markerFont) + 8,
    );
    const textLeft = indent + markerWidth;
    const lines = layoutInlines(item.inlines, {
      baseFont: font,
      color: SHARE_COLORS.text,
      maxWidth: Math.max(80, context.width - textLeft),
      measure: context.measure,
      onFallbackFormula: context.onFallbackFormula,
    });
    lines.forEach((line, position) => {
      rows.push({
        height: line.height,
        render: (x: number, y: number) => [
          ...(position === 0
            ? [
                {
                  kind: "text" as const,
                  x: x + indent,
                  y: y + Math.round((line.height - markerFont.size * 1.2) / 2),
                  text: marker,
                  font: markerFont,
                  color: SHARE_COLORS.muted,
                },
              ]
            : []),
          ...shift(line.items, x + textLeft, y),
        ],
      });
    });
    rows.push(spacer(4));
  }
  return rows;
}

function listMarker(item: ShareListItem): string {
  if (typeof item.checked === "boolean") return item.checked ? "☑" : "☐";
  if (item.ordered) return `${item.index}.`;
  return item.depth % 2 === 0 ? "•" : "◦";
}

function codeRows(
  block: Extract<ShareBlock, { type: "code" }>,
  context: BlockContext,
): FlowRow[] {
  const font = mono(13.5);
  const lineHeight = 22;
  const innerWidth = context.width - CODE_PADDING * 2;
  const wrapped: string[] = [];
  for (const raw of block.lines) {
    const text = raw.replace(/\t/g, "    ");
    if (context.measure.measureText(text, font) <= innerWidth) {
      wrapped.push(text);
      continue;
    }
    let current = "";
    for (const character of text) {
      const candidate = current + character;
      if (
        current &&
        context.measure.measureText(candidate, font) > innerWidth
      ) {
        wrapped.push(current);
        current = character;
      } else {
        current = candidate;
      }
    }
    wrapped.push(current);
  }
  const rows: FlowRow[] = [];
  const label = block.lang.trim();
  const headerHeight = label ? 26 : 0;
  const width = context.width;
  rows.push(spacer(6));
  if (label) {
    rows.push({
      height: headerHeight,
      render: (x, y) => [
        {
          kind: "rect",
          x,
          y,
          width,
          height: headerHeight,
          fill: SHARE_COLORS.codeGutter,
          radius: 0,
        },
        {
          kind: "text",
          x: x + CODE_PADDING,
          y: y + 6,
          text: label,
          font: mono(11.5, 600),
          color: SHARE_COLORS.faint,
        },
      ],
    });
  }
  rows.push({
    height: CODE_PADDING,
    render: (x, y) => [
      {
        kind: "rect",
        x,
        y,
        width,
        height: CODE_PADDING,
        fill: SHARE_COLORS.codeBackground,
      },
    ],
  });
  wrapped.forEach((line) => {
    rows.push({
      height: lineHeight,
      render: (x, y) => [
        {
          kind: "rect",
          x,
          y,
          width,
          height: lineHeight,
          fill: SHARE_COLORS.codeBackground,
        },
        {
          kind: "text",
          x: x + CODE_PADDING,
          y: y + Math.round((lineHeight - font.size * 1.2) / 2),
          text: line,
          font,
          color: SHARE_COLORS.codeText,
        },
      ],
    });
  });
  rows.push({
    height: CODE_PADDING,
    render: (x, y) => [
      {
        kind: "rect",
        x,
        y,
        width,
        height: CODE_PADDING,
        fill: SHARE_COLORS.codeBackground,
      },
    ],
  });
  rows.push(spacer(8));
  return rows;
}

interface TablePlan {
  widths: number[];
  font: ShareFont;
  keptColumns: number;
  totalColumns: number;
}

/**
 * 合同 R6 的宽表规则：
 *   1. 先整体等比缩放；
 *   2. 缩到最小可读字号（`SHARE_MIN_TABLE_FONT`）仍放不下 → 保留前若干列，
 *      并在图上标注「完整表格见原对话」。
 */
export function planTableColumns(
  columns: string[][],
  contentWidth: number,
  measure: ShareMeasureContext,
  baseSize = 14,
): TablePlan {
  const baseFont = sans(baseSize);
  const natural = columns.map((cell) => {
    const widest = cell.reduce(
      (max, text) => Math.max(max, measure.measureText(text, baseFont)),
      0,
    );
    return Math.min(contentWidth, widest + TABLE_CELL_PADDING * 2);
  });
  const total = natural.reduce((sum, width) => sum + width, 0) || 1;
  if (total <= contentWidth) {
    const extra = (contentWidth - total) / natural.length;
    return {
      widths: natural.map((width) => width + extra),
      font: baseFont,
      keptColumns: natural.length,
      totalColumns: natural.length,
    };
  }
  const scale = contentWidth / total;
  const scaledSize = Math.round(baseSize * scale * 10) / 10;
  if (scaledSize >= SHARE_MIN_TABLE_FONT) {
    return {
      widths: natural.map((width) => width * scale),
      font: sans(scaledSize),
      keptColumns: natural.length,
      totalColumns: natural.length,
    };
  }
  const minScale = SHARE_MIN_TABLE_FONT / baseSize;
  const atMin = natural.map((width) => width * minScale);
  const widths: number[] = [];
  let used = 0;
  for (const width of atMin) {
    if (widths.length && used + width > contentWidth) break;
    widths.push(width);
    used += width;
  }
  if (!widths.length) widths.push(contentWidth);
  return {
    widths,
    font: sans(SHARE_MIN_TABLE_FONT),
    keptColumns: widths.length,
    totalColumns: natural.length,
  };
}

function tableRows(
  block: Extract<ShareBlock, { type: "table" }>,
  context: BlockContext,
): FlowRow[] {
  const columnCount = Math.max(
    block.header.length,
    ...block.rows.map((row) => row.length),
    1,
  );
  const columns: string[][] = [];
  for (let index = 0; index < columnCount; index += 1) {
    columns.push([
      inlinesToPlainText(block.header[index] || []),
      ...block.rows.map((row) => inlinesToPlainText(row[index] || [])),
    ]);
  }
  const plan = planTableColumns(columns, context.width, context.measure);
  if (plan.keptColumns < plan.totalColumns) context.onTruncatedTable();
  const kept = plan.keptColumns;
  const headerFont: ShareFont = { ...plan.font, weight: 600 };
  const rowHeight = Math.round(plan.font.size * 2.4);
  const tableWidth = plan.widths.reduce((sum, width) => sum + width, 0);

  const drawRow = (
    cells: ShareInline[][],
    font: ShareFont,
    background?: string,
  ): FlowRow => ({
    height: rowHeight,
    render: (x, y) => {
      const items: ShareDrawItem[] = [];
      if (background) {
        items.push({
          kind: "rect",
          x,
          y,
          width: tableWidth,
          height: rowHeight,
          fill: background,
        });
      }
      let cursor = x;
      for (let index = 0; index < kept; index += 1) {
        const width = plan.widths[index];
        items.push({
          kind: "rect",
          x: cursor,
          y,
          width,
          height: rowHeight,
          stroke: SHARE_COLORS.tableBorder,
          lineWidth: 1,
        });
        const text = inlinesToPlainText(cells[index] || []);
        if (text) {
          items.push({
            kind: "text",
            x: cursor + TABLE_CELL_PADDING,
            y: y + Math.round((rowHeight - font.size * 1.2) / 2),
            text: clipToWidth(
              text,
              width - TABLE_CELL_PADDING * 2,
              font,
              context.measure,
            ),
            font,
            color: font.weight >= 600 ? SHARE_COLORS.text : SHARE_COLORS.muted,
          });
        }
        cursor += width;
      }
      return items;
    },
  });

  const rows: FlowRow[] = [spacer(8)];
  rows.push(drawRow(block.header, headerFont, SHARE_COLORS.tableHeader));
  for (const row of block.rows) rows.push(drawRow(row, plan.font));
  if (plan.keptColumns < plan.totalColumns) {
    const noteFont = sans(12, 400, true);
    rows.push({
      height: 24,
      render: (x, y) => [
        {
          kind: "text",
          x,
          y: y + 6,
          text: context.labels.tableTruncated,
          font: noteFont,
          color: SHARE_COLORS.faint,
        },
      ],
    });
  }
  rows.push(spacer(8));
  return rows;
}

function clipToWidth(
  text: string,
  maxWidth: number,
  font: ShareFont,
  measure: ShareMeasureContext,
): string {
  if (measure.measureText(text, font) <= maxWidth) return text;
  let current = "";
  for (const character of text) {
    if (measure.measureText(`${current}${character}…`, font) > maxWidth) break;
    current += character;
  }
  return `${current}…`;
}

function mathRows(
  block: Extract<ShareBlock, { type: "math" }>,
  context: BlockContext,
): FlowRow[] {
  const measured = context.measure.measureMath?.(block.tex, true, context.width);
  if (!measured) {
    context.onFallbackFormula();
    return paragraphRows(
      [{ type: "text", text: block.tex, code: true }],
      context,
      mono(14),
    );
  }
  const scale = Math.min(1, context.width / Math.max(1, measured.width));
  const width = measured.width * scale;
  const height = measured.height * scale;
  return [
    spacer(10),
    {
      height: Math.round(height),
      render: (x, y) => [
        {
          kind: "math",
          x: x + Math.round((context.width - width) / 2),
          y,
          width,
          height,
          tex: block.tex,
          display: true,
        },
      ],
    },
    spacer(10),
  ];
}

function imageRows(
  block: Extract<ShareBlock, { type: "image" }>,
  context: BlockContext,
  maxHeight: number,
): FlowRow[] {
  const natural = context.measure.imageSize?.(block.src);
  if (!natural || !(natural.width > 0) || !(natural.height > 0)) return [];
  const scale = Math.min(
    1,
    context.width / natural.width,
    maxHeight / natural.height,
  );
  const width = Math.round(natural.width * scale);
  const height = Math.round(natural.height * scale);
  return [
    spacer(8),
    {
      height,
      render: (x, y) => [
        {
          kind: "image",
          x,
          y,
          width,
          height,
          src: block.src,
          radius: 12,
        },
      ],
    },
    spacer(8),
  ];
}

function blockRows(
  block: ShareBlock,
  context: BlockContext,
  maxImageHeight: number,
): FlowRow[] {
  switch (block.type) {
    case "heading":
      return headingRows(block, context);
    case "paragraph":
      return paragraphRows(block.inlines, context);
    case "quote":
      return quoteRows(block, context);
    case "list":
      return listRows(block, context);
    case "code":
      return codeRows(block, context);
    case "table":
      return tableRows(block, context);
    case "math":
      return mathRows(block, context);
    case "image":
      return imageRows(block, context, maxImageHeight);
    case "rule":
      return [
        spacer(10),
        {
          height: 1,
          render: (x, y) => [
            {
              kind: "line",
              x,
              y,
              width: context.width,
              color: SHARE_COLORS.rule,
              thickness: 1,
            },
          ],
        },
        spacer(10),
      ];
    default:
      return [];
  }
}

