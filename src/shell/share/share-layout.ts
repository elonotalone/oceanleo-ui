/** 画笔与测量器必须用同一个字体串，否则量出来的宽度对不上画出来的字。 */
export function shareFontCss(font: ShareFont): string {
  const style = font.italic ? "italic " : "";
  const family = font.mono ? SHARE_MONO_STACK : SHARE_SANS_STACK;
  return `${style}${font.weight} ${font.size}px ${family}`;
}

function sans(size: number, weight = 400, italic = false): ShareFont {
  return { size, weight, mono: false, italic };
}

function mono(size: number, weight = 400): ShareFont {
  return { size, weight, mono: true };
}

