interface InlineAtom {
  text: string;
  width: number;
  font: ShareFont;
  color: string;
  href?: string;
  strike?: boolean;
  code?: boolean;
  math?: { tex: string; height: number };
  breakBefore?: boolean;
  hardBreak?: boolean;
}

interface LaidLine {
  height: number;
  items: ShareDrawItem[];
}

const CJK = /[\u2e80-\u9fff\u3000-\u303f\uff00-\uffef]/;

/** 断行单元：CJK 逐字，拉丁按词（连着后面的空格一起走）。 */
function textAtoms(text: string): string[] {
  const out: string[] = [];
  let word = "";
  for (const character of text) {
    if (character === "\n") {
      if (word) out.push(word);
      word = "";
      out.push("\n");
      continue;
    }
    if (CJK.test(character)) {
      if (word) out.push(word);
      word = "";
      out.push(character);
      continue;
    }
    word += character;
    if (character === " " || character === "\t") {
      out.push(word);
      word = "";
    }
  }
  if (word) out.push(word);
  return out;
}

interface InlineLayoutOptions {
  baseFont: ShareFont;
  color: string;
  maxWidth: number;
  measure: ShareMeasureContext;
  lineHeightRatio?: number;
  align?: "left" | "right";
  /** 统计兜底公式的次数。 */
  onFallbackFormula?: () => void;
}

function atomsFromInlines(
  inlines: readonly ShareInline[],
  options: InlineLayoutOptions,
): InlineAtom[] {
  const out: InlineAtom[] = [];
  for (const inline of inlines) {
    if (inline.type === "math") {
      const measured = options.measure.measureMath?.(
        inline.tex,
        false,
        options.maxWidth,
      );
      if (measured) {
        out.push({
          text: inline.tex,
          width: measured.width,
          font: options.baseFont,
          color: options.color,
          math: { tex: inline.tex, height: measured.height },
        });
        continue;
      }
      options.onFallbackFormula?.();
      const font = mono(options.baseFont.size - 1);
      out.push({
        text: inline.tex,
        width: options.measure.measureText(inline.tex, font),
        font,
        color: options.color,
        code: true,
      });
      continue;
    }
    const font: ShareFont = {
      size: inline.code ? options.baseFont.size - 1 : options.baseFont.size,
      weight: inline.bold ? 600 : options.baseFont.weight,
      mono: Boolean(inline.code),
      italic: Boolean(inline.italic),
    };
    const color = inline.href
      ? SHARE_COLORS.accent
      : inline.code
        ? SHARE_COLORS.text
        : options.color;
    for (const piece of textAtoms(inline.text)) {
      if (piece === "\n") {
        out.push({
          text: "",
          width: 0,
          font,
          color,
          hardBreak: true,
        });
        continue;
      }
      out.push({
        text: piece,
        width: options.measure.measureText(piece, font),
        font,
        color,
        href: inline.href,
        strike: inline.strike,
        code: inline.code,
      });
    }
  }
  return out;
}

/** 把一串行内片段排成若干行；每行是一个不可再分的排版原子。 */
function layoutInlines(
  inlines: readonly ShareInline[],
  options: InlineLayoutOptions,
): LaidLine[] {
  const atoms = atomsFromInlines(inlines, options);
  const ratio = options.lineHeightRatio ?? 1.62;
  const lines: LaidLine[] = [];
  let row: InlineAtom[] = [];
  let used = 0;

  const flush = () => {
    if (!row.length) {
      lines.push({ height: Math.round(options.baseFont.size * ratio), items: [] });
      return;
    }
    // 行尾空白不参与对齐宽度。
    while (row.length && !row[row.length - 1].text.trim()) row.pop();
    const width = row.reduce((sum, atom) => sum + atom.width, 0);
    const textHeight = Math.round(
      Math.max(...row.map((atom) => atom.font.size)) * ratio,
    );
    const mathHeight = Math.max(
      0,
      ...row.map((atom) => (atom.math ? atom.math.height + 6 : 0)),
    );
    const height = Math.max(textHeight, mathHeight);
    const startX = options.align === "right" ? options.maxWidth - width : 0;
    let cursor = startX;
    const items: ShareDrawItem[] = [];
    let run: { text: string; x: number; atom: InlineAtom } | null = null;
    const closeRun = () => {
      if (!run) return;
      items.push({
        kind: "text",
        x: run.x,
        y: Math.round((height - run.atom.font.size * 1.2) / 2),
        text: run.text,
        font: run.atom.font,
        color: run.atom.color,
        underline: Boolean(run.atom.href),
        strike: Boolean(run.atom.strike),
      });
      run = null;
    };
    for (const atom of row) {
      if (atom.hardBreak) continue;
      if (atom.math) {
        closeRun();
        items.push({
          kind: "math",
          x: cursor,
          y: Math.round((height - atom.math.height) / 2),
          width: atom.width,
          height: atom.math.height,
          tex: atom.math.tex,
          display: false,
        });
        cursor += atom.width;
        continue;
      }
      const sameRun =
        run &&
        run.atom.font.size === atom.font.size &&
        run.atom.font.weight === atom.font.weight &&
        run.atom.font.mono === atom.font.mono &&
        run.atom.font.italic === atom.font.italic &&
        run.atom.color === atom.color &&
        Boolean(run.atom.href) === Boolean(atom.href) &&
        Boolean(run.atom.strike) === Boolean(atom.strike);
      if (sameRun && run) run.text += atom.text;
      else {
        closeRun();
        run = { text: atom.text, x: cursor, atom };
      }
      cursor += atom.width;
    }
    closeRun();
    lines.push({ height, items });
    row = [];
    used = 0;
  };

  for (const atom of atoms) {
    if (atom.hardBreak) {
      flush();
      continue;
    }
    if (used > 0 && used + atom.width > options.maxWidth) flush();
    row.push(atom);
    used += atom.width;
  }
  if (row.length) flush();
  if (!lines.length) {
    lines.push({ height: Math.round(options.baseFont.size * ratio), items: [] });
  }
  return lines;
}

