export const W3_M4_MESSAGES = Object.fromEntries(LOCALES.map(locale => [locale,
  copyDictionaryFrom(SOURCE, locale === 'zh' ? SOURCE : locale === 'zh-TW' ? TW : EN),
])) as Record<Locale, Record<string, string>>;
export type NativeTaskCopy = ReturnType<typeof nativeTaskText>;
export function nativeTaskText(locale = 'en') {
  const table = locale === 'zh' ? SOURCE : locale === 'zh-TW' ? TW : EN;
  return (key: keyof typeof SOURCE, vars?: Record<string, string | number>) =>
    table[key].replace(/\{(\w+)\}/g, (match, name: string) => vars?.[name] === undefined ? match : String(vars[name]));
}
/** Shared-core generated UI notices use source-text keys; program-authored output remains verbatim. */
export function nativeTaskTranslate(locale = 'en') {
  const table = W3_M4_MESSAGES[(locale in W3_M4_MESSAGES ? locale : 'en') as Locale];
  return (source: string, vars?: Record<string, string | number>) => {
    const translated = table[source] || (locale === 'zh' || !/[\u3400-\u9fff]/u.test(source) ? source : nativeTaskText(locale)('unknown'));
    return translated.replace(/\{(\w+)\}/g, (match, name: string) => vars?.[name] === undefined ? match : String(vars[name]));
  };
}
