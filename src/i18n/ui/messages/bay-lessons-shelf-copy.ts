function dictionaryFor(messages: LocaleMessages): Record<string, string> {
  return Object.fromEntries(
    (Object.keys(sourceKeys) as MessageName[]).map((name) => [
      sourceKeys[name],
      messages[name],
    ]),
  );
}

export const BAY_LESSONS_SHELF_SOURCE = sourceKeys;

export const BAY_LESSONS_SHELF_MESSAGES = Object.fromEntries(
  LOCALES.map((locale) => [locale, dictionaryFor(translations[locale])]),
) as Record<Locale, Record<string, string>>;
